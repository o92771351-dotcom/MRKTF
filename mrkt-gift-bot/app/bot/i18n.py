def start_text(user_name: str, source_name: str, is_demo: bool) -> str:
    lines = [
        f"Привет, {user_name}! 👋",
        "",
        "Я отслеживаю предложения коллекционных подарков на маркетплейсе "
        "<b>MRKT</b>, нахожу монохромные варианты по вашим фильтрам и присылаю "
        "подходящие лоты с фото, ценой, оценкой выгоды и ссылкой.",
        "",
        "<b>С чего начать</b>",
        "1️⃣ /filters — создайте фильтр (коллекция, цена, модель, фон, символ, монохром).",
        "2️⃣ /search — проверить рынок прямо сейчас, не дожидаясь расписания.",
        "3️⃣ /status — что подключено, как часто проверяю и что было последним.",
        "",
        "Дальше я буду присылать карточки лотов сам — по расписанию каждого фильтра. "
        "Один и тот же лот повторно не приходит, если цена не снизилась существенно.",
        "",
        f"<b>Источник данных:</b> <code>{source_name}</code>",
    ]
    if is_demo:
        lines += ["", DEMO_BANNER]
    lines += ["", CREDITS_LINE]
    return "\n".join(lines)


